// Builds src/college-standings.json: each college school's ESPN conference
// group and team id, per standings board (user, November 11, 2026: "Start
// the college conference standings"). ESPN's whole-division standings are
// 2.4 to 6 MB (too much to parse in a feed build: Cloudflare 1102), so the
// app reads only the school's conference (`standings?group=<id>`, about
// 300 KB), and this file says which group that is.
//
//   node scripts/make-college-standings.mjs [--from=<dir>]
//
// --from reads saved copies (<board path with _>.json; FCS adds _group81)
// instead of ESPN. Rerun after conference realignment (each July) or when a
// college school is added; tests/college-standings.mjs fails for a college
// school with the sport and no entry.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createSourceFetch,SOURCE_TTL} from '../src/source-fetch.mjs';
import {rosterSocialInstagrams} from '../src/roster-socials.js';
import {schoolModuleDeps} from '../tests/school-module-deps.mjs';
import {COLLEGE_STANDINGS_BOARDS,COLLEGE_HOCKEY_PAGES,independentGroup,parseChnStandings} from '../src/college-standings.mjs';

const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const schools=JSON.parse(read('../src/schools.json')),sponsored=JSON.parse(read('../src/sponsored-sports.json'));
const from=(process.argv.find(a=>a.startsWith('--from='))||'').slice(7)||null;
const source=read('../src/index.js').replace(/^import .*;\n/gm,'').replace('export default{','const handler={');
const deps={...schoolModuleDeps,createSourceFetch,SOURCE_TTL,schools,sponsoredSports:sponsored,rosterSocialInstagrams,extractText:()=>{throw Error('Unexpected PDF');},fetch:()=>{throw Error('Unexpected network request');}};
const w=Function(...Object.keys(deps),source+';return {scoreboardTeamMatchesSchool,catalogSchool};')(...Object.values(deps));

async function payload(board,query){
  const name=`${board.replace(/\//g,'_')}${query?`_${query.replace(/\W/g,'')}`:''}.json`;
  if(from&&existsSync(`${from}/${name}`))return JSON.parse(readFileSync(`${from}/${name}`,'utf8'));
  const url=`https://site.api.espn.com/apis/v2/sports/${board}/standings${query?`?${query}`:''}`;
  const r=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0','Accept':'application/json'}});
  if(!r.ok)throw Error(`${url}: HTTP ${r.status}`);
  return r.json();
}
const entriesOf=node=>[...(node?.standings?.entries||[]).map(e=>({e,group:node})),...(node?.children||[]).flatMap(entriesOf)];

const hockeyMissing=[];
const out={note:'Generated by scripts/make-college-standings.mjs from ESPN standings and College Hockey News; do not edit by hand.',generated:new Date().toISOString().slice(0,10),boards:{}},report=[];
for(const [board,spec] of Object.entries(COLLEGE_STANDINGS_BOARDS)){
  // Each top-level conference (not its divisions) is the group read.
  const conferences=[];
  for(const query of spec.reads){const p=await payload(board,query);for(const c of p.children||[])if(!independentGroup(c.name))conferences.push(c);}
  const teams=conferences.flatMap(c=>entriesOf(c).map(({e})=>({team:e.team,group:Number(c.id),conference:c.name})));
  const map={};
  for(const school of schools){
    if((school.level&&school.level!=='college')||school.pro)continue;
    if(!(sponsored[school.id]||[]).includes(spec.sport))continue;
    const hits=teams.filter(t=>w.scoreboardTeamMatchesSchool(t.team,w.catalogSchool(school.id)||school));
    const ids=[...new Set(hits.map(h=>h.team.id))];
    if(ids.length===1)map[school.id]=[hits[0].group,String(ids[0])];
    else report.push(`${board} ${school.id}: ${ids.length?`${ids.length} teams (${hits.map(h=>`${h.team.displayName} ${h.conference}`).join('; ')})`:'no team'}`);
  }
  // One ESPN team for two schools is a wrong match.
  const seen=new Map();for(const [id,[,team]] of Object.entries(map)){if(seen.has(team))report.push(`${board} ESPN team ${team}: ${seen.get(team)} and ${id}`);seen.set(team,id);}
  out.boards[board]=Object.fromEntries(Object.entries(map).sort(([a],[b])=>a.localeCompare(b)));
  console.log(`${board}: ${Object.keys(map).length} schools, ${conferences.length} conferences`);
}
// College hockey from College Hockey News (one page per gender; ESPN has no
// conference records or points for hockey): {school id: [conference, CHN
// team id]}. A school without a team of that gender is simply not on the page.
async function page(board,url){
  const name=`${board.replace(/\//g,'_')}.html`;
  if(from&&existsSync(`${from}/${name}`))return readFileSync(`${from}/${name}`,'utf8');
  const r=await fetch(url,{headers:{'User-Agent':'Mozilla/5.0','Accept':'text/html'}});
  if(!r.ok)throw Error(`${url}: HTTP ${r.status}`);
  return r.text();
}
// CHN's own spellings the app's matcher cannot take (Nov 12, 2026): "Miami"
// alone would also be Miami (FL), "Massachusetts" reads as a one-word
// nickname, and "Mass.-Lowell" and "Long Island" are no catalog name.
const CHN_NAMES={'miami-oh':'Miami','umass':'Massachusetts','umass-lowell':'Mass.-Lowell','liu':'Long Island'};
for(const [board,spec] of Object.entries(COLLEGE_HOCKEY_PAGES)){
  const conferences=parseChnStandings(await page(board,spec.url));
  const teams=conferences.flatMap(c=>c.teams.map(t=>({team:{id:t.id,location:t.name,displayName:t.name,shortDisplayName:t.slug.replace(/-/g,' ')},conference:c.conference})));
  const map={};
  for(const school of schools){
    if((school.level&&school.level!=='college')||school.pro)continue;
    if(!(sponsored[school.id]||[]).includes('Hockey'))continue;
    const hits=teams.filter(t=>CHN_NAMES[school.id]?t.team.location===CHN_NAMES[school.id]:w.scoreboardTeamMatchesSchool(t.team,w.catalogSchool(school.id)||school));
    const ids=[...new Set(hits.map(h=>h.team.id))];
    if(ids.length===1)map[school.id]=[hits[0].conference,ids[0]];
    else if(ids.length)report.push(`${board} ${school.id}: ${ids.length} teams (${hits.map(h=>`${h.team.displayName} ${h.conference}`).join('; ')})`);
    else hockeyMissing.push(`${board} ${school.id}`);
  }
  const seen=new Map();for(const [id,[,team]] of Object.entries(map)){if(seen.has(team))report.push(`${board} CHN team ${team}: ${seen.get(team)} and ${id}`);seen.set(team,id);}
  out.boards[board]=Object.fromEntries(Object.entries(map).sort(([a],[b])=>a.localeCompare(b)));
  console.log(`${board}: ${Object.keys(map).length} schools, ${conferences.length} conferences`);
}
// One line per board: {school id: [ESPN group, ESPN team id]}; hockey
// [conference, CHN team id].
const lines=Object.entries(out.boards).map(([board,map])=>`  ${JSON.stringify(board)}:${JSON.stringify(map)}`);
writeFileSync(new URL('../src/college-standings.json',import.meta.url),`{"note":${JSON.stringify(out.note)},"generated":${JSON.stringify(out.generated)},"boards":{\n${lines.join(',\n')}\n}}\n`);
console.log(report.length?`Not mapped (${report.length}):\n${report.join('\n')}`:'Every school mapped.');
if(hockeyMissing.length)console.log(`No hockey team of that gender on College Hockey News (${hockeyMissing.length}):\n${hockeyMissing.join('\n')}`);
